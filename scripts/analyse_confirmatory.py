"""Frozen confirmatory analysis of EXP-001 to EXP-003 (trust.hypotheses; decision D-011).

    PYTHONPATH=src .venv/bin/python scripts/analyse_confirmatory.py --exp EXP-001|EXP-002|EXP-003

Reads results/confirmatory/<config>/results.json, writes results/confirmatory/analysis/<EXP>.json,
research/experiments/<EXP>/results_tables.md and research/experiments/<EXP>/figures/*.svg,
plus a SHA-256 manifest of everything it wrote. Every number comes from the result files.
"""

from __future__ import annotations

import argparse
import json
from collections import namedtuple
from pathlib import Path

from trust.hypotheses import analyse_exp001, analyse_exp002, analyse_exp003, clean
from trust.provenance import REPO_ROOT, git_revision, sha256_file
from trust.report import fmt, svg_contrast
from trust.results import import_result

IV = namedtuple("IV", "mean boot_lo boot_hi n")
CONF = REPO_ROOT / "results" / "confirmatory"


def load(stem: str) -> tuple[dict, Path]:
    p = CONF / stem / "results.json"
    return import_result(p), p


def _iv(mean, lo, hi, n=0) -> IV:
    f = lambda x: float("nan") if x is None else x  # noqa: E731
    return IV(f(mean), f(lo), f(hi), n)


def tables_exp001(a: dict) -> tuple[str, list]:
    L = ["<!-- SPDX-License-Identifier: LicenseRef-TRUST-NC-Research-1.0 -->",
         "# EXP-001 generated result tables", "",
         "Generated by `scripts/analyse_confirmatory.py` from `results/confirmatory/EXP-001/results.json`. Simulated. "
         "D = tau-b(SHRINK_5) minus tau-b(MEAN), unitless. Intervals: 95% percentile bootstrap over seeds (10,000 resamples).", "",
         f"Runs: {a['counts']['runs']}, ok {a['counts']['ok']}, failed {len(a['counts']['failed'])}.", "",
         "## Primary hypothesis H1", "",
         "| Estimand | Estimate | Two-sided 95% | One-sided 95% lower bound | Cells | Verdict (frozen rule) |", "|---|---|---|---|---|---|",
         f"| Dbar | {fmt(a['H1']['Dbar'])} | {fmt(a['H1']['lo95'])} to {fmt(a['H1']['hi95'])} | {fmt(a['H1']['lower_one_sided_95'])} | {a['H1']['n_cells']} | {a['H1']['verdict']} |", "",
         "## D per noise level (A-2, descriptive)", "", "| sigma (stars) | Cells | D_sigma | Two-sided 95% |", "|---|---|---|---|"]
    for s, p in a["D_sigma"].items():
        L.append(f"| {s} | {p['n_cells']} | {fmt(p['mean'])} | {fmt(p['lo95'])} to {fmt(p['hi95'])} |")
    L += ["", f"Direction depends on the noise level (intervals exclude 0 with opposite signs): {'yes' if a['direction_depends_on_sigma'] else 'no'}.", "",
          "## Per cell", "", "| Cell | nu | sigma | Seeds | Mean D | SD | Bootstrap 95% | t 95% | Mean/SD |", "|---|---|---|---|---|---|---|---|---|"]
    for cid, c in a["per_cell"].items():
        L.append(f"| {cid} | {c['values']['nu']} | {c['values']['sigma']} | {c['n']} | {fmt(c['mean'])} | {fmt(c['sd'])} | {fmt(c['boot_lo'])} to {fmt(c['boot_hi'])} | {fmt(c['t_lo'])} to {fmt(c['t_hi'])} | {fmt(c['std_effect'], 2)} |")
    L += ["", "## H1b: ordering by review count", "", "| sigma | E[D] nu=3 | nu=10 | nu=30 | Ordered 3 > 10 > 30 | nu 3 and nu 30 intervals overlap |", "|---|---|---|---|---|---|"]
    for r in a["H1b"]["rows"]:
        m = r["means_by_nu"]
        L.append(f"| {r['sigma']} | {fmt(m['3'])} | {fmt(m['10'])} | {fmt(m['30'])} | {'yes' if r['ordered_decreasing'] else 'no'} | {'yes' if r['nu_low_high_intervals_overlap'] else 'no'} |")
    L += ["", f"H1b verdict (frozen rule): {a['H1b']['verdict']} (ordered at {a['H1b']['n_sigma_ordered']} of 3 noise levels; overlap at {a['H1b']['n_sigma_overlap']} of 3).", "",
          "## Secondary family (Holm, alpha 0.05, one-sided bootstrap p-values; D-011)", "",
          "| Contrast | Estimate | Two-sided 95% | p | Holm-adjusted p | Rejects H0 |", "|---|---|---|---|---|---|"]
    for k, h in a["holm"].items():
        s = a["secondary"][k]
        L.append(f"| {k} | {fmt(s['estimate'])} | {fmt(s['lo95'])} to {fmt(s['hi95'])} | {fmt(h['p'])} | {fmt(h['p_holm'])} | {'yes' if h['reject'] else 'no'} |")
    L += ["", "Per noise level for the secondary arms (descriptive):", "", "| Contrast | sigma | Mean | Two-sided 95% |", "|---|---|---|---|"]
    for k, s in a["secondary"].items():
        for lev, p in (s.get("per_sigma") or {}).items():
            L.append(f"| {k} | {lev} | {fmt(p['mean'])} | {fmt(p['lo95'])} to {fmt(p['hi95'])} |")
    labs = [f"cell nu={c['values']['nu']}, sigma={c['values']['sigma']}" for c in a["per_cell"].values()]
    ivs = [_iv(c["mean"], c["boot_lo"], c["boot_hi"], c["n"]) for c in a["per_cell"].values()]
    for s, p in a["D_sigma"].items():
        labs.append(f"D_sigma, sigma={s}")
        ivs.append(_iv(p["mean"], p["lo95"], p["hi95"]))
    labs.append("Dbar (all 9 cells)")
    ivs.append(_iv(a["H1"]["Dbar"], a["H1"]["lo95"], a["H1"]["hi95"]))
    desc = ("Simulated, confirmatory. Dot-and-interval chart of D = tau-b(SHRINK_5) minus tau-b(MEAN) (unitless): nine cells "
            "(20 seeds each), the three per-noise-level means D_sigma and the pooled Dbar. Dots are means; bars are two-sided 95% "
            "percentile bootstrap intervals (10,000 resamples, seeds resampled within cells). Dashed line: zero.")
    figs = [("FIG-001.svg", svg_contrast("FIG-001. EXP-001: SHRINK_5 minus MEAN in Kendall tau-b", desc, labs, ivs,
                                         "difference in Kendall tau-b (unitless)"), desc)]
    return "\n".join(L) + "\n", figs


def tables_exp002(a: dict) -> tuple[str, list]:
    L = ["<!-- SPDX-License-Identifier: LicenseRef-TRUST-NC-Research-1.0 -->", "# EXP-002 generated result tables", "",
         "Generated by `scripts/analyse_confirmatory.py` from `results/confirmatory/EXP-002/results.json`. Simulated; sigma = 1.0. "
         "D = tau-b(arm) minus tau-b(MEAN). Contrasts are same-seed paired differences of D between factor levels, per stratum and "
         "averaged over strata with equal weight; 95% percentile bootstrap (10,000 resamples).", "",
         f"Runs: {a['counts']['runs']}, ok {a['counts']['ok']}, failed {len(a['counts']['failed'])}.", "",
         "## D per cell (SHRINK_5 minus MEAN)", "", "| Cell | nu | lambda | gamma | Seeds | Mean D | Bootstrap 95% |", "|---|---|---|---|---|---|---|"]
    for cid, c in a["D_per_cell"].items():
        v = c["values"]
        L.append(f"| {cid} | {v['nu']} | {v['lam']} | {v['gamma']} | {c['n']} | {fmt(c['mean'])} | {fmt(c['boot_lo'])} to {fmt(c['boot_hi'])} |")
    labs, ivs = [], []
    for arm, e in a["contrasts"].items():
        L += ["", f"## {arm}", ""]
        if "holm" in e:
            L += [f"Frozen H1 (lambda) verdict: {e['H1_lambda_verdict']}.", "",
                  "| Contrast | Estimate (avg over strata) | Two-sided 95% | p (two-sided) | Holm-adjusted p | Rejects H0 | Strata excluding 0 |", "|---|---|---|---|---|---|---|"]
            for k, x in e["contrasts"].items():
                h = e["holm"][k]
                L.append(f"| {k} | {fmt(x['estimate'])} | {fmt(x['lo95'])} to {fmt(x['hi95'])} | {fmt(h['p'])} | {fmt(h['p_holm'])} | {'yes' if h['reject'] else 'no'} | {x['n_strata_excluding_zero']} of {len(x['per_stratum'])} |")
        else:
            L += [e["note"] + ".", "", "| Contrast | Estimate | Two-sided 95% | Strata excluding 0 |", "|---|---|---|---|"]
            for k, x in e["contrasts"].items():
                L.append(f"| {k} | {fmt(x['estimate'])} | {fmt(x['lo95'])} to {fmt(x['hi95'])} | {x['n_strata_excluding_zero']} of {len(x['per_stratum'])} |")
        L += ["", "| Contrast | Stratum | Pairs | Mean | Bootstrap 95% |", "|---|---|---|---|---|"]
        for k, x in e["contrasts"].items():
            for r in x["per_stratum"]:
                st = ", ".join(f"{kk}={vv}" for kk, vv in r["stratum"].items())
                L.append(f"| {k} | {st} | {r['n_pairs']} | {fmt(r['mean'])} | {fmt(r['boot_lo'])} to {fmt(r['boot_hi'])} |")
            labs.append(f"{arm.split(' ')[0]}: {k}")
            ivs.append(_iv(x["estimate"], x["lo95"], x["hi95"]))
    desc = ("Simulated, confirmatory. Dot-and-interval chart of how D = tau-b(arm) minus tau-b(MEAN) changes with reporting selection "
            "(lambda 2 minus 0) and exposure coupling (gamma -0.5 or 0.5 minus 0), for SHRINK_5 and LCB. Each row averages six or four "
            "strata of 20 same-seed pairs; bars are two-sided 95% stratified bootstrap intervals. Dashed line: zero.")
    figs = [("FIG-002.svg", svg_contrast("FIG-002. EXP-002: change in D with lambda and gamma", desc, labs, ivs,
                                         "difference of differences in Kendall tau-b (unitless)"), desc)]
    return "\n".join(L) + "\n", figs


def tables_exp003(a: dict) -> tuple[str, list]:
    L = ["<!-- SPDX-License-Identifier: LicenseRef-TRUST-NC-Research-1.0 -->", "# EXP-003 generated result tables", "",
         "Generated by `scripts/analyse_confirmatory.py` from the EXP-003 result files and EXP-001/EXP-002. Simulated. "
         "D = tau-b(arm) minus tau-b(MEAN); two-sided 95% stratified bootstrap intervals (10,000 resamples).", "",
         f"EXP-001 reference Dbar (SHRINK_5 minus MEAN): {fmt(a['EXP-001_Dbar'])}.", "",
         "| Sub-analysis | Runs | ok | failed |", "|---|---|---|---|"]
    for k, c in a["counts"].items():
        L.append(f"| {k} | {c['runs']} | {c['ok']} | {len(c['failed'])} |")
    L += ["", "## Pooled Dbar per sensitivity condition", "",
          "| Condition | Contrast | Cells | Dbar | Two-sided 95% | Frozen invalidation criterion met |", "|---|---|---|---|---|---|"]
    rows = []
    s1 = a["S1"]
    rows.append(("S1, n >= 1", "SHRINK_5 - MEAN", s1["min1"], "yes" if s1["min1"]["invalidates"] else "no"))
    rows.append(("S1, n >= 5", "SHRINK_5 - MEAN", s1["min5"], "n/a (reported)"))
    for arm, lab in (("SHRINK_5_UP", "S2, centre m + 0.5"), ("SHRINK_5_DOWN", "S2, centre m - 0.5")):
        rows.append((lab, f"{arm} - MEAN", a["S2"][arm], "yes" if a["S2"][arm]["sign_reversal"] else "no"))
    rows.append(("S2 check, centre m", "SHRINK_5 - MEAN", a["S2"]["SHRINK_5 (check, equals EXP-001)"], "n/a"))
    rows.append(("S3, truth theta_rep (pooled)", "SHRINK_5 - MEAN", a["S3"]["pooled_theta_rep"], "see S3 table"))
    for q, p in a["S4"]["by_quality"].items():
        rows.append((f"S4, quality {q}", "SHRINK_5 - MEAN", p, "yes" if p["sign_reversal"] else "no"))
    for lab, con, p, crit in rows:
        L.append(f"| {lab} | {con} | {p['n_cells']} | {fmt(p['Dbar'])} | {fmt(p['lo95'])} to {fmt(p['hi95'])} | {crit} |")
    L += ["", "## D per noise level (A-2, descriptive)", "", "| Condition | sigma | D_sigma | Two-sided 95% |", "|---|---|---|---|"]
    for lab, con, p, _ in rows:
        for s, q in (p.get("D_sigma") or {}).items():
            L.append(f"| {lab} ({con}) | {s} | {fmt(q['mean'])} | {fmt(q['lo95'])} to {fmt(q['hi95'])} |")
    fl = s1["min5"]["flagged_fewer_than_20_products"]
    L += ["", f"S1 n >= 5: catalogues with fewer than 20 evaluated products, by cell (flagged, not dropped): {fl if fl else 'none'}.", "",
          "## S3: sign of D under the two truth definitions", "",
          "| Cell | nu | lambda | gamma | D vs theta | 95% | D vs theta_rep | 95% | Sign differs |", "|---|---|---|---|---|---|---|---|---|"]
    for r in a["S3"]["rows"]:
        v, t1, t2 = r["values"], r["theta"], r["theta_rep"]
        L.append(f"| {r['cell_id']} | {v['nu']} | {v['lam']} | {v['gamma']} | {fmt(t1['mean'])} | {fmt(t1['boot_lo'])} to {fmt(t1['boot_hi'])} | {fmt(t2['mean'])} | {fmt(t2['boot_lo'])} to {fmt(t2['boot_hi'])} | {'yes' if r['sign_differs'] else 'no'} |")
    L += ["", f"S3: sign differs in {a['S3']['n_sign_differs']} of {a['S3']['n_cells']} cells ({a['S3']['n_sign_differs_lambda2']} of the 6 lambda = 2 cells); "
          f"frozen invalidation criterion (majority) met: {'yes' if a['S3']['invalidates'] else 'no'}.", "",
          f"Summary: S1 invalidates: {'yes' if s1['min1']['invalidates'] else 'no'}; S2: {'yes' if a['S2']['invalidates'] else 'no'}; "
          f"S3: {'yes' if a['S3']['invalidates'] else 'no'}; S4: {'yes' if a['S4']['invalidates'] else 'no'}."]
    labs = ["EXP-001 reference (centre m)"] + [lab for lab, _, _, _ in rows]
    ivs = [_iv(a["S2"]["SHRINK_5 (check, equals EXP-001)"]["Dbar"], a["S2"]["SHRINK_5 (check, equals EXP-001)"]["lo95"],
               a["S2"]["SHRINK_5 (check, equals EXP-001)"]["hi95"])] + [_iv(p["Dbar"], p["lo95"], p["hi95"]) for _, _, p, _ in rows]
    desc = ("Simulated, confirmatory. Dot-and-interval chart of the pooled difference in Kendall tau-b against MEAN under each "
            "EXP-003 sensitivity condition, next to the EXP-001 reference. Each row pools 9 or 12 cells of 20 seeds; bars are "
            "two-sided 95% stratified bootstrap intervals (10,000 resamples). Dashed line: zero.")
    figs = [("FIG-003.svg", svg_contrast("FIG-003. EXP-003: pooled D under each sensitivity condition", desc, labs, ivs,
                                         "difference in Kendall tau-b (unitless)"), desc)]
    return "\n".join(L) + "\n", figs


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--exp", required=True, choices=["EXP-001", "EXP-002", "EXP-003"])
    a = p.parse_args()
    inputs = {}
    if a.exp == "EXP-001":
        doc, path = load("EXP-001")
        inputs[str(path.relative_to(REPO_ROOT))] = sha256_file(path)
        res = analyse_exp001(doc)
        md, figs = tables_exp001(clean(res))
    elif a.exp == "EXP-002":
        doc, path = load("EXP-002")
        inputs[str(path.relative_to(REPO_ROOT))] = sha256_file(path)
        res = analyse_exp002(doc)
        md, figs = tables_exp002(clean(res))
    else:
        docs = {}
        for stem in ("EXP-001", "EXP-002", "EXP-003-S1-min1", "EXP-003-S1-min5", "EXP-003-S2", "EXP-003-S3", "EXP-003-S4"):
            docs[stem], path = load(stem)
            inputs[str(path.relative_to(REPO_ROOT))] = sha256_file(path)
        res = analyse_exp003(docs["EXP-001"], docs["EXP-002"], docs["EXP-003-S1-min1"], docs["EXP-003-S1-min5"],
                             docs["EXP-003-S2"], docs["EXP-003-S3"], docs["EXP-003-S4"])
        md, figs = tables_exp003(clean(res))
    res = clean(res)
    out_json = CONF / "analysis" / f"{a.exp}.json"
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(res, indent=1, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")
    exp_dir = REPO_ROOT / "research" / "experiments" / a.exp
    (exp_dir / "figures").mkdir(parents=True, exist_ok=True)
    (exp_dir / "results_tables.md").write_text(md, encoding="utf-8")
    for name, svg, _ in figs:
        (exp_dir / "figures" / name).write_text(svg, encoding="utf-8")
    written = [out_json, exp_dir / "results_tables.md", *[exp_dir / "figures" / n for n, _, _ in figs]]
    manifest = {"generator": "scripts/analyse_confirmatory.py (trust.hypotheses)", "exp_id": a.exp,
                "code_revision": git_revision(), "inputs": inputs,
                "outputs": {str(w.relative_to(REPO_ROOT)): sha256_file(w) for w in written},
                "figures": {n: d for n, _, d in figs}}
    (CONF / "analysis" / f"{a.exp}.manifest.json").write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
