"""M4 exploratory confounder checks (EXPLORATORY; never changes a frozen verdict).

    PYTHONPATH=src .venv/bin/python scripts/m4_exploratory.py

E1 (committed results only): SHRINK_5 minus MEAN on the secondary metrics of EXP-001
    (Spearman rho, precision at 10, regret at 10, RMSE), pooled and per noise level, with the
    same stratified bootstrap as the frozen analysis. Addresses the construct confounder
    "the conclusion depends on choosing Kendall tau-b".
E2 (deterministic regeneration of the frozen EXP-001 catalogues, read-only): share of products
    whose MEAN score is tied with at least one other product, the share of tied pairs, and the
    share of products with exactly one review, per cell. The tau-b of MEAN and SHRINK_5 is
    recomputed and compared with the committed result file (reproduction check).
    Addresses the protocol confounder "ties in MEAN scores at small n".

Writes results/exploratory/m4-sensitivity/{m4_exploratory.json, m4_exploratory.md, manifest.json}.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from trust.analysis import paired_differences, pooled_by_level, pooled_stratified
from trust.config import expand_cells, load_config
from trust.estimators import mean_score, shrink_score
from trust.metrics import kendall_tau_b
from trust.provenance import REPO_ROOT, git_revision, sha256_file
from trust.results import import_result
from trust.simulate import seed_streams, simulate_catalogue

OUT = REPO_ROOT / "results" / "exploratory" / "m4-sensitivity"
RES = REPO_ROOT / "results" / "confirmatory" / "EXP-001" / "results.json"
CFG = REPO_ROOT / "experiments" / "EXP-001.json"
METRICS = [("tau_b", 1), ("spearman", 1), ("precision_at_k", 1), ("regret_at_k", -1), ("rmse", -1)]


def e1(doc: dict) -> dict:
    out = {}
    for metric, sign in METRICS:
        diffs = paired_differences(doc, "SHRINK_5", "MEAN", metric)
        diffs = {k: sign * v for k, v in diffs.items()}
        pooled = pooled_stratified(diffs)
        out[metric] = {
            "orientation": "SHRINK_5 minus MEAN" if sign == 1 else "MEAN minus SHRINK_5 (positive favours SHRINK_5)",
            "pooled": {k: pooled[k] for k in ("n_cells", "dbar", "lo95", "hi95")},
            "per_sigma": pooled_by_level(doc, diffs, "sigma"),
        }
    return out


def tie_stats(s: np.ndarray) -> tuple[float, float]:
    _, inv, cnt = np.unique(s, return_inverse=True, return_counts=True)
    share_products = float(np.mean(cnt[inv] > 1))
    n = s.size
    tied_pairs = float(np.sum(cnt * (cnt - 1) / 2))
    return share_products, tied_pairs / (n * (n - 1) / 2)


def e2(cfg: dict, doc: dict) -> dict:
    committed = {(r["cell_id"], r["seed_index"]): r for r in doc["runs"]}
    rows, max_abs_dev = {}, 0.0
    for cell in expand_cells(cfg):
        tp, tpair, one, shr_tp = [], [], [], []
        for seed in range(cfg["n_seeds"]):
            cat = simulate_catalogue(cell.params, seed_streams(cfg["seed_root"], cfg["exp_number"], seed))
            sm = mean_score(cat.counts)
            ss = shrink_score(cat.counts, 5)
            a, b = tie_stats(sm)
            tp.append(a)
            tpair.append(b)
            shr_tp.append(tie_stats(ss)[0])
            one.append(float(np.mean(cat.n == 1)))
            ref = committed[(cell.cell_id, seed)]["arms"]
            max_abs_dev = max(max_abs_dev, abs(kendall_tau_b(sm, cat.theta) - ref["MEAN"]["tau_b"]),
                              abs(kendall_tau_b(ss, cat.theta) - ref["SHRINK_5"]["tau_b"]))
        rows[cell.cell_id] = {
            "values": cell.values,
            "share_products_tied_mean": float(np.mean(tp)),
            "share_pairs_tied_mean": float(np.mean(tpair)),
            "share_products_tied_shrink5": float(np.mean(shr_tp)),
            "share_one_review": float(np.mean(one)),
            "n_seeds": cfg["n_seeds"],
        }
    return {"per_cell": rows, "max_abs_tau_b_deviation_vs_committed": max_abs_dev}


def f(x, d=4):
    return "n/a" if x is None else f"{x:.{d}f}"


def markdown(r: dict) -> str:
    L = ["<!-- SPDX-License-Identifier: LicenseRef-TRUST-NC-Research-1.0 -->",
         "# M4 exploratory confounder checks (EXPLORATORY)", "",
         "Generated by `scripts/m4_exploratory.py`. Simulated. Exploratory: not registered, not part of any frozen "
         "verdict, and never replacing one. Intervals: two-sided 95% stratified bootstrap over seeds within cells "
         "(10,000 resamples, seed 20261124), as in the frozen analysis.", "",
         "## E1. SHRINK_5 versus MEAN on the secondary metrics of EXP-001 (committed results)", "",
         "Positive values favour SHRINK_5 for every row (regret and RMSE are oriented as MEAN minus SHRINK_5).", "",
         "| Metric | Pooled (9 cells) | sigma 0.5 | sigma 1.0 | sigma 1.5 |", "|---|---|---|---|---|"]
    for m, v in r["E1"].items():
        p = v["pooled"]
        cells = [f"{f(p['dbar'])} ({f(p['lo95'])} to {f(p['hi95'])})"]
        for s in ("0.5", "1.0", "1.5"):
            q = v["per_sigma"][s]
            cells.append(f"{f(q['mean'])} ({f(q['lo95'])} to {f(q['hi95'])})")
        L.append(f"| {m} | " + " | ".join(cells) + " |")
    L += ["", "Units: tau-b, Spearman and precision at 10 are unitless; regret at 10 and RMSE are in stars.", "",
          "## E2. Ties in MEAN scores (regenerated EXP-001 catalogues)", "",
          f"Reproduction check: the largest absolute difference between the recomputed and committed tau-b of MEAN "
          f"and SHRINK_5 over 180 runs is {r['E2']['max_abs_tau_b_deviation_vs_committed']:.3g}.", "",
          "| Cell | nu | sigma | Products tied (MEAN) | Pairs tied (MEAN) | Products tied (SHRINK_5) | Products with one review |",
          "|---|---|---|---|---|---|---|"]
    for cid, c in r["E2"]["per_cell"].items():
        L.append(f"| {cid} | {c['values']['nu']} | {c['values']['sigma']} | {f(c['share_products_tied_mean'], 3)} | "
                 f"{f(c['share_pairs_tied_mean'], 3)} | {f(c['share_products_tied_shrink5'], 3)} | {f(c['share_one_review'], 3)} |")
    L += ["", "Shares are means over 20 seeds per cell. Products with zero reviews all receive the catalogue mean "
          "under MEAN and SHRINK_5, so they form one tied group under both arms."]
    return "\n".join(L) + "\n"


def main() -> int:
    git = git_revision()  # read before writing any output
    doc = import_result(RES)
    cfg = load_config(CFG)
    res = {"label": "exploratory", "simulated": True, "source_result": str(RES.relative_to(REPO_ROOT)),
           "source_result_sha256": sha256_file(RES), "config": str(CFG.relative_to(REPO_ROOT)),
           "config_sha256_file": sha256_file(CFG), "E1": e1(doc), "E2": e2(cfg, doc)}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "m4_exploratory.json").write_text(json.dumps(res, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    (OUT / "m4_exploratory.md").write_text(markdown(res), encoding="utf-8")
    man = {"generator": "scripts/m4_exploratory.py", "git": git,
           "outputs": {p: sha256_file(OUT / p) for p in ("m4_exploratory.json", "m4_exploratory.md")}}
    (OUT / "manifest.json").write_text(json.dumps(man, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print((OUT / "m4_exploratory.md").read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
